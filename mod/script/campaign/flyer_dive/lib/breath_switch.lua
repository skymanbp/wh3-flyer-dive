-- breath_switch.lua — the breath-while-engaged setting (D10): decide on / off, and when off keep CA's locks by hand
-- 接战时吹息开关（D10）：判定开 / 关；关时由脚本按原版的两条限制逐兵锁住吹息
--
-- [D10, owner ruling 2026-11-18] The pack ships CA's special_ability_to_invalid_usage_flags table without the
-- engaged_in_melee / grounded rows of 20 breath abilities: that is the "on" state, and it needs no script, no
-- MCT and no memreader Plus. The table cannot change while the game runs, so "off" is done here: every
-- poll_ms of battle time each listed ability of each unit is disabled while one of its locks holds and enabled
-- again when none does. The locks are the dropped rows, per ability (data/breath_rows.lua, generated by the
-- build from the same rows):
--   * "in_melee"   -- row engaged_in_melee; unit:is_in_melee()
--   * "not_flying" -- row grounded;         not unit:is_currently_flying()
-- (battle_unit API, CA's documentation: disable_special_ability "Disables or re-enables the ability (true for
-- disabling it)", it only touches the instance the unit owns.)
-- [D14, owner 2026-11-18: "in multiplayer the MCT settings follow the host's, they do not go out of step; just do
-- it normally"] A multiplayer CAMPAIGN battle reads the setting like a single-player one: MCT hands every machine
-- of a multiplayer campaign the host's settings and locks the other players' options (MCT's own scripts:
-- systems/sync/main.lua MctMpInitialLoad / MctMpFinalized, objects/options/obj.lua mct_lock_reason_mp_client).
-- A multiplayer battle OUTSIDE a campaign (custom / quick / ranked) keeps "on": there MCT gives each machine its
-- own global settings (systems/registry/main.lua, context "battle") and nothing can agree between the players
-- (lib/cave_common.lua start_battle), so two different settings would lock abilities on one machine only.
-- / 多人战役的战斗按 MCT 的设置（MCT 把主机的设置发给每一台机器）；战役之外的多人战斗固定为开（那里 MCT 各读各的）。
--
-- Pure module: no core / bm / get_mct here (the battle entry battle/mod/flyer_breath.lua passes them in), so it
-- runs unchanged in LuaJIT tests. / 纯模块：不直接调用 core / bm / get_mct，由战斗入口传入。

local M = {}

-- on, why: whether breath may be used while engaged in this battle.
-- `rows` is data/breath_rows; `mp` / `from_campaign` the battle's bm:is_multiplayer() / is_from_campaign();
-- `read_mct(mod_key, option_key)` returns the setting MCT holds (nil when MCT is not installed).
function M.decide(rows, mp, from_campaign, read_mct)
    local default = rows.default_on == true
    if mp and not from_campaign then
        return true, "multiplayer battle outside a campaign: MCT shares no setting between the players there, "
            .. "breath while engaged stays on"
    end
    if type(read_mct) ~= "function" then
        return default, "default (MCT not installed)"
    end
    local ok, value = pcall(read_mct, rows.mct_mod, rows.mct_option)
    if not ok then
        return default, "default (reading MCT failed: " .. tostring(value) .. ")"
    end
    if type(value) ~= "boolean" then
        return default, "default (MCT holds no setting: " .. tostring(value) .. ")"
    end
    return value, mp and "MCT, multiplayer campaign" or "MCT"
end

-- Whether an ability with these locks must be disabled now.
function M.locked(locks, in_melee, flying)
    for _, lock in ipairs(locks) do
        if lock == "in_melee" and in_melee then return true end
        if lock == "not_flying" and not flying then return true end
    end
    return false
end

-- A keeper: keeper:step(each_unit) walks every unit (each_unit(fn) calls fn(unit) once per unit) and disables or
-- enables the listed abilities each unit owns. A unit's owned abilities are read once, by unique_ui_id. Only a
-- change of state calls the game. Counters: set (disabled), released (enabled again), units (seen with a listed
-- ability), errors (a unit whose calls failed; the walk goes on).
function M.keeper(rows)
    local abilities = rows.abilities
    local k = { owned = {}, state = {}, set = 0, released = 0, units = 0, errors = 0, last_error = nil }

    local function owned_of(unit, uid)
        local list = k.owned[uid]
        if list then return list end
        list = {}
        for _, key in ipairs(unit:owned_non_passive_special_abilities() or {}) do
            if abilities[key] then list[#list + 1] = key end
        end
        k.owned[uid] = list
        if #list > 0 then k.units = k.units + 1 end
        return list
    end

    local function visit(unit)
        local uid = unit:unique_ui_id()
        local list = owned_of(unit, uid)
        if #list == 0 then return end
        local in_melee = unit:is_in_melee() and true or false
        local flying = unit:is_currently_flying() and true or false
        local state = k.state[uid]
        if not state then state = {}; k.state[uid] = state end
        for _, key in ipairs(list) do
            local want = M.locked(abilities[key], in_melee, flying)
            if (state[key] or false) ~= want then
                unit:disable_special_ability(key, want)
                state[key] = want
                if want then k.set = k.set + 1 else k.released = k.released + 1 end
            end
        end
    end

    function k:step(each_unit)
        each_unit(function(unit)
            local ok, problem = pcall(visit, unit)
            if not ok then
                k.errors = k.errors + 1
                k.last_error = tostring(problem)
            end
        end)
    end

    function k:counts()
        return ("breath locks set %d, released %d, units with a listed breath %d, unit errors %d"):format(
            k.set, k.released, k.units, k.errors)
    end

    return k
end

return M
