"""TEST-ONLY packs for the flyer take-off comparisons.

[AIR-DIVE-TAKEOFF-W1 2026-11-12] Nothing here ships: flyer_dive_takeoff.pack is
built by build_air_dive_minimod.py and is not touched. Each pack carries the air-dive
movement recorder plus:

  --base probe   recorder only (vanilla flight data)
  --base full    the stand-alone air-dive content (flight tables, impact
                 stage, the flyer rows with their mass cut, the breath
                 usage-flag table) WITHOUT its take-off and dive-rule scripts
                 and without the breath switch scripts (so breath while
                 engaged is simply on, the switch's default) [D10: one pack]
  --rule         + the shipped take-off scripts (battle entry, rule module,
                 generated site table: build_air_dive_minimod.takeoff_entries)
  --record       (with --rule) + pin_on_hit_probe.lua, which writes what the
                 caves recorded and answered to pin_probe.txt and reads
                 pin_probe.cfg ("window <ticks>" = one window for every
                 body size instead of the ruled ones, "mode <1|2>"; mode 2 =
                 hits recorded, the game's own engaged check answers: the
                 vanilla arm with the record)

Without --rule the pack leaves the game's take-off as it is (pure vanilla).

  --trace-from P [d10-1118, for D11: the take-off gap] a copy of the BUILT pack P (normally the main
                 pack built with build_air_dive_minimod.py --probe, so it carries the movement recorder)
                 with its take-off site table swapped for the traced one (pipelines/takeoff_trace_site.lua,
                 generated by takeoff_trace_asm.py; refused when stale) and the recorder added. The pack
                 replaces the shipped one in the run (--test-pack <its name>); "trace 1" in pin_probe.cfg
                 turns the trace on. Not with --base / --rule / --record.

usage: build_pin_on_hit_probe.py --out X.pack --base probe|full
       [--rule [--record]] [--impact-stage B]
       build_pin_on_hit_probe.py --out X.pack --trace-from <built pack>
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import rolepath

import air_dive_rules
import build_air_dive_minimod as mini
from packfile import PACK_TYPE_MOD, write_pack_file

assert rolepath          # imported for its side effect: the role directories on sys.path
PROBE_SOURCE = HERE / "pin_on_hit_probe.lua"
PROBE_PACK_PATH = "script/battle/mod/pin_on_hit_probe.lua"


def record_entry():
    return (PROBE_PACK_PATH, PROBE_SOURCE.read_text("utf-8").replace("\r\n", "\n").encode("utf-8"))


def full_entries():
    anims, _manifest = mini.anim_entries()
    dbs, _n_ent, _n_loco = mini.db_entries(mini.GAME_DIR / "db.pack")
    impact, repoint, _report = mini.impact_entries(mini.GAME_DIR / "db.pack")
    renamed, _counts = mini.rename_entries(mini.GAME_DIR / "db.pack", repoint)
    usage, _removed, _breath = mini.usage_entries(mini.GAME_DIR)
    return anims + dbs + impact + renamed + usage


SHIPPED_NAMES = ("flyer_dive_takeoff.pack",)


def trace_entries(built_pack):
    """[d10-1118] Every entry of ``built_pack``, its take-off site table swapped for the traced one, plus
    the recorder. Refuses: a stale traced table, a pack without exactly one take-off site table, a pack
    that already carries the recorder."""
    import takeoff_trace_asm
    from packfile import PackFile
    traced = takeoff_trace_asm.check_site_file().replace("\r\n", "\n").encode("utf-8")
    site = air_dive_rules.TAKEOFF_SITE_LUA_PATH.lower()
    with PackFile.open(str(built_pack)) as pack:
        entries = [(e.path, pack.read_file(e)) for e in pack.entries]
    norm = [path.replace("\\", "/").lower() for path, _data in entries]
    sites = [i for i, path in enumerate(norm) if path == site]
    if len(sites) != 1:
        raise SystemExit(f"[pin_probe] REFUSING: {built_pack} carries {len(sites)} {site}, want 1")
    if PROBE_PACK_PATH.lower() in norm:
        raise SystemExit(f"[pin_probe] REFUSING: {built_pack} already carries {PROBE_PACK_PATH}")
    entries[sites[0]] = (entries[sites[0]][0], traced)
    return entries + [record_entry()]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--base", choices=("probe", "full"))
    ap.add_argument("--trace-from", help="a built pack: its copy with the traced take-off caves and the recorder")
    ap.add_argument("--rule", action="store_true")
    ap.add_argument("--record", action="store_true")
    ap.add_argument("--impact-stage", choices=air_dive_rules.IMPACT_STAGES,
                    default=air_dive_rules.IMPACT_STAGE)
    args = ap.parse_args(argv)
    if Path(args.out).name.lower() in SHIPPED_NAMES:
        raise SystemExit(f"[pin_probe] REFUSING: {args.out} is a shipped pack's name")
    if args.trace_from:
        if args.base or args.rule or args.record:
            raise SystemExit("[pin_probe] REFUSING: --trace-from copies a built pack; no --base / --rule / --record")
        size = write_pack_file(args.out, trace_entries(args.trace_from), PACK_TYPE_MOD)
        print(f"wrote {args.out} ({size} bytes): {args.trace_from} with the traced take-off caves + recorder")
        return
    if not args.base:
        raise SystemExit("[pin_probe] REFUSING: --base probe|full (or --trace-from) is required")
    if args.record and not args.rule:
        raise SystemExit("[pin_probe] REFUSING: --record reads the caves' buffer, it needs --rule")
    air_dive_rules.IMPACT_STAGE = args.impact_stage
    entries = [mini.probe_entry("probe_only" if args.base == "probe" else "with_dive")]
    if args.base == "full":
        entries += full_entries()
    if args.rule:
        entries += mini.takeoff_entries()
    if args.record:
        entries.append(record_entry())
    size = write_pack_file(args.out, entries, PACK_TYPE_MOD)
    print(f"wrote {args.out} ({size} bytes): base {args.base}"
          + (f" impact {args.impact_stage}" if args.base == "full" else "")
          + (" + take-off rule scripts" if args.rule else "")
          + (" + take-off recorder" if args.record else ""))


if __name__ == "__main__":
    main()
